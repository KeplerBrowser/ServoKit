const out = process.argv[2];
if (!out) {
  console.error('usage: bun generate.mjs <output-folder>');
  process.exit(1);
}
const tidy = (svg) => svg.split('\n').map((line) => line.trimEnd()).filter(Boolean).join('\n') + '\n';
for (const [name, theme] of Object.entries(THEMES)) {
  writeFileSync(join(out, `banner-${name}.svg`), tidy(banner(theme)));
  console.log(`wrote banner-${name}.svg`);
}
