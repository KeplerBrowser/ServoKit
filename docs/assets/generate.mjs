// Generates the README banner in this folder: banner-light.svg and
// banner-dark.svg. Text is converted to outlines from the Inter font
// (SIL Open Font License 1.1), so the banner looks the same everywhere.
//
// Edit this script, then regenerate. Don't hand-edit the SVG files.
//
//   cd "$(mktemp -d)"
//   bun add opentype.js@1.3.4 @fontsource/inter@5.3.0
//   bun /path/to/ExplorerKit/docs/assets/generate.mjs /path/to/ExplorerKit/docs/assets
//
// Dependencies are loaded from the current directory, so this repository
// needs no extra packages.
import { createRequire } from 'node:module';
