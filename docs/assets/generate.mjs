const require = createRequire(join(process.cwd(), 'noop.js'));
const opentype = require('opentype.js');
const font = (weight) =>
  opentype.loadSync(require.resolve(`@fontsource/inter/files/inter-latin-${weight}-normal.woff`));
const FONTS = { 400: font(400), 500: font(500), 600: font(600), 700: font(700), 800: font(800) };

// Returns an outlined path for `str`, plus its width. `ls` is letter spacing in em.
function text(str, { size, weight = 400, x = 0, y = 0, ls = 0, anchor = 'start' }) {
  const f = FONTS[weight];
  const scale = size / f.unitsPerEm;
  const glyphs = f.stringToGlyphs(str);
  const advance = (i) =>
    glyphs[i].advanceWidth * scale +
    (i < glyphs.length - 1 ? f.getKerningValue(glyphs[i], glyphs[i + 1]) * scale + ls * size : 0);
  let width = 0;
  for (let i = 0; i < glyphs.length; i++) width += advance(i);
  let cx = anchor === 'middle' ? x - width / 2 : anchor === 'end' ? x - width : x;
  const parts = [];
  for (let i = 0; i < glyphs.length; i++) {
    parts.push(glyphs[i].getPath(cx, y, size).toPathData(1));
    cx += advance(i);
  }
  return { d: parts.join(''), width };
}

