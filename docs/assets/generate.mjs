function defs(t, W, H) {
  return `
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${t.bg0}"/>
      <stop offset="1" stop-color="${t.bg1}"/>
    </linearGradient>
    <linearGradient id="accent" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${t.accentA}"/>
      <stop offset="1" stop-color="${t.accentB}"/>
    </linearGradient>
    <linearGradient id="heroFill" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${t.accentA}" stop-opacity="0.55"/>
      <stop offset="1" stop-color="${t.accentB}" stop-opacity="0.55"/>
    </linearGradient>
    <radialGradient id="glowA" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="${t.glowA}" stop-opacity="${t.glowAOpacity}"/>
      <stop offset="1" stop-color="${t.glowA}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glowB" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="${t.glowB}" stop-opacity="${t.glowBOpacity}"/>
      <stop offset="1" stop-color="${t.glowB}" stop-opacity="0"/>
    </radialGradient>
    <pattern id="grid" width="32" height="32" patternUnits="userSpaceOnUse">
      <path d="M32 0H0V32" fill="none" stroke="${t.grid}" stroke-opacity="${t.gridOpacity}"/>
    </pattern>
    <clipPath id="frame"><rect width="${W}" height="${H}" rx="28"/></clipPath>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="150%">
      <feDropShadow dx="0" dy="14" stdDeviation="16" flood-color="${t.shadow}" flood-opacity="${t.shadowOpacity}"/>
    </filter>
  </defs>`;
}

function svgDoc(W, H, title, desc, t, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d">
  <title id="t">${title}</title>
  <desc id="d">${desc}</desc>
  <!-- Generated by docs/assets/generate.mjs. Text is outlined from Inter (SIL Open Font License 1.1). -->
  ${defs(t, W, H)}
  <g clip-path="url(#frame)">
    <rect width="${W}" height="${H}" fill="url(#bg)"/>
    <rect width="${W}" height="${H}" fill="url(#grid)"/>
    ${body}
  </g>
  <rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" rx="28" fill="none" stroke="${t.frame}" stroke-opacity="0.08"/>
</svg>
`;
}

