import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(packageRoot, "../..");
const sourceCratesDir = path.join(repoRoot, "crates");
const sourceHostModuleDir = path.join(
  sourceCratesDir,
  "servokit-host-android",
  "android"
);
const generatedCratesDir = path.join(packageRoot, "crates");
const generatedHostModuleDir = path.join(
  packageRoot,
  "android",
  "servokit-android-host"
);
const marker = ".servokit-package-generated";
const ignoredDirs = new Set([
  "target",
  "build",
  ".gradle",
  ".cxx",
  ".kotlin",
]);

function assertInsidePackage(target) {
  const relative = path.relative(packageRoot, target);
  if (relative === "" || relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new Error(`Refusing to touch path outside package root: ${target}`);
  }
}

function removeGenerated(target) {
  assertInsidePackage(target);
  if (!fs.existsSync(target)) {
    return;
  }

  if (!fs.existsSync(path.join(target, marker))) {
    throw new Error(`Refusing to remove non-generated path: ${target}`);
  }

  fs.rmSync(target, { recursive: true, force: true });
}

function copySourceTree(from, to) {
  fs.cpSync(from, to, {
    recursive: true,
    filter(source) {
      const relative = path.relative(from, source);
      if (relative === "") {
        return true;
      }

      const parts = relative.split(path.sep);
      if (parts.some((part) => ignoredDirs.has(part))) {
        return false;
      }

      return path.basename(source) !== "local.properties";
    },
  });

  fs.writeFileSync(path.join(to, marker), "generated by npm prepack\n");
}

function sync() {
  if (!fs.existsSync(sourceCratesDir) || !fs.existsSync(sourceHostModuleDir)) {
    throw new Error(
      `ServoKit source inputs were not found under ${repoRoot}; run this from the ServoKit repository checkout.`
    );
  }

  removeGenerated(generatedCratesDir);
  removeGenerated(generatedHostModuleDir);
  copySourceTree(sourceCratesDir, generatedCratesDir);
  copySourceTree(sourceHostModuleDir, generatedHostModuleDir);
}

if (process.argv.includes("--clean")) {
  removeGenerated(generatedCratesDir);
  removeGenerated(generatedHostModuleDir);
} else {
  sync();
}
